/**
 * Viloyat nomi bo'yicha uning tumanlarini topish
 */
export function getDistrictsByRegion(regionName: string): string[] {
  if (!regionName) return [];
  const found = UZBEKISTAN_REGIONS.find(
    r => r.name.toLowerCase() === regionName.toLowerCase() ||
         r.id.toLowerCase() === regionName.toLowerCase()
  );
  return found ? found.districts : [];
}

/**
 * Mavjud matnli manzilni tahlil qilib viloyat, tuman va ko'chani ajratib olish
 */
export function parseAddress(addressString: string): { region: string; district: string; street: string } {
  if (!addressString) {
    return { region: '', district: '', street: '' };
  }

  // 1. Viloyatni aniqlash
  let matchedRegion = '';
  for (const reg of UZBEKISTAN_REGIONS) {
    if (addressString.toLowerCase().includes(reg.name.toLowerCase())) {
      matchedRegion = reg.name;
      break;
    }
  }

  // Agar to'g'ridan-to'g'ri topilmasa, qisqartmalar tekshiriladi
  if (!matchedRegion) {
    if (addressString.toLowerCase().includes('toshkent sh') || addressString.toLowerCase().includes('tashkent')) {
      matchedRegion = 'Toshkent shahri';
    } else if (addressString.toLowerCase().includes('toshkent vil')) {
      matchedRegion = 'Toshkent viloyati';
    } else if (addressString.toLowerCase().includes('samarqand')) {
      matchedRegion = 'Samarqand viloyati';
    } else if (addressString.toLowerCase().includes('farg')) {
      matchedRegion = 'Farg‘ona viloyati';
    } else if (addressString.toLowerCase().includes('andijon')) {
      matchedRegion = 'Andijon viloyati';
    } else if (addressString.toLowerCase().includes('namangan')) {
      matchedRegion = 'Namangan viloyati';
    } else if (addressString.toLowerCase().includes('buxoro')) {
      matchedRegion = 'Buxoro viloyati';
    } else if (addressString.toLowerCase().includes('qashqadaryo')) {
      matchedRegion = 'Qashqadaryo viloyati';
    } else if (addressString.toLowerCase().includes('surxondaryo')) {
      matchedRegion = 'Surxondaryo viloyati';
    } else if (addressString.toLowerCase().includes('xorazm')) {
      matchedRegion = 'Xorazm viloyati';
    } else if (addressString.toLowerCase().includes('navoiy')) {
      matchedRegion = 'Navoiy viloyati';
    } else if (addressString.toLowerCase().includes('jizzax')) {
      matchedRegion = 'Jizzax viloyati';
    } else if (addressString.toLowerCase().includes('sirdaryo')) {
      matchedRegion = 'Sirdaryo viloyati';
    } else if (addressString.toLowerCase().includes('qoraqalpoq')) {
      matchedRegion = 'Qoraqalpog‘iston Respublikasi';
    }
  }

  // 2. Tumanni aniqlash
  let matchedDistrict = '';
  if (matchedRegion) {
    const districts = getDistrictsByRegion(matchedRegion);
    for (const dist of districts) {
      // "Chilonzor tumani" -> "Chilonzor"
      const baseName = dist.replace(/ tumani| shahri/i, '').trim();
      if (addressString.toLowerCase().includes(baseName.toLowerCase())) {
        matchedDistrict = dist;
        break;
      }
    }
  } else {
    // Viloyat aniqlanmagan bo'lsa barcha tumanlar ichidan qidirish
    for (const reg of UZBEKISTAN_REGIONS) {
      for (const dist of reg.districts) {
        const baseName = dist.replace(/ tumani| shahri/i, '').trim();
        if (addressString.toLowerCase().includes(baseName.toLowerCase())) {
          matchedRegion = reg.name;
          matchedDistrict = dist;
          break;
        }
      }
      if (matchedDistrict) break;
    }
  }

  // 3. Ko'cha / Uy qismini tozalash
  let street = addressString;
  if (matchedRegion) {
    street = street.replace(new RegExp(matchedRegion, 'gi'), '');
    street = street.replace(/toshkent sh\.|toshkent vil\./gi, '');
  }
  if (matchedDistrict) {
    const baseName = matchedDistrict.replace(/ tumani| shahri/i, '').trim();
    street = street.replace(new RegExp(matchedDistrict, 'gi'), '');
    street = street.replace(new RegExp(baseName, 'gi'), '');
  }
  street = street.replace(/^[\s,.\-_/]+|[\s,.\-_/]+$/g, '').trim();

  return {
    region: matchedRegion,
    district: matchedDistrict,
    street
  };
}

/**
 * Viloyat, tuman va ko'chani bitta chiroyli manzil qatoriga yig'ish
 */
export function formatAddress(region: string, district: string, street?: string): string {
  const parts: string[] = [];
  if (region) parts.push(region);
  if (district) parts.push(district);
  if (street && street.trim()) parts.push(street.trim());
  return parts.join(', ');
}
